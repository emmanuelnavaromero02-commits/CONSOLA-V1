def _git_object_sha(kind: bytes, raw: bytes) -> bytes:
    header = kind + b" " + str(len(raw)).encode("ascii") + b"\0"
    return hashlib.sha1(header + raw, usedforsecurity=False).digest()


def _git_stream_blob_sha(stream: Any, *, size: int) -> bytes:
    digest = hashlib.sha1(usedforsecurity=False)
    digest.update(b"blob " + str(size).encode("ascii") + b"\0")
    remaining = size
    while remaining:
        chunk = stream.read(min(1024 * 1024, remaining))
        if not chunk:
            raise AuthorityError("source archive file payload differs")
        digest.update(chunk)
        remaining -= len(chunk)
    if stream.read(1):
        raise AuthorityError("source archive file payload differs")
    return digest.digest()


def _single_gzip_payload(descriptor: int, expected: os.stat_result) -> Any:
    """Inflate exactly one gzip member from a held regular-file descriptor."""
    os.lseek(descriptor, 0, os.SEEK_SET)
    expanded = tempfile.TemporaryFile()  # noqa: SIM115 -- returned to caller
    inflater = zlib.decompressobj(wbits=16 + zlib.MAX_WBITS)
    compressed = 0
    expanded_size = 0
    try:
        while compressed < expected.st_size:
            chunk = os.read(descriptor, min(1024 * 1024, expected.st_size - compressed))
            if not chunk:
                raise AuthorityError("source archive was truncated")
            compressed += len(chunk)
            pending = chunk
            while pending:
                output = inflater.decompress(pending, 1024 * 1024)
                pending = inflater.unconsumed_tail
                if output:
                    expanded_size += len(output)
                    if expanded_size > MAX_EXPANDED_ARCHIVE:
                        raise AuthorityError(
                            "source archive expanded size exceeds bound"
                        )
                    expanded.write(output)
                if inflater.unused_data:
                    raise AuthorityError(
                        "source archive has concatenated or trailing gzip data"
                    )
                if inflater.eof:
                    if pending or compressed != expected.st_size:
                        raise AuthorityError(
                            "source archive has concatenated or trailing gzip data"
                        )
                    break
            if inflater.eof:
                break
        if compressed != expected.st_size or not inflater.eof:
            raise AuthorityError("source archive gzip member is incomplete")
        tail = inflater.flush()
        if tail:
            expanded_size += len(tail)
            if expanded_size > MAX_EXPANDED_ARCHIVE:
                raise AuthorityError("source archive expanded size exceeds bound")
            expanded.write(tail)
        expanded.flush()
        expanded.seek(0)
        return expanded
    except Exception:
        expanded.close()
        raise


def _archive_tree_sha(
    source: Path | int,
    *,
    source_ref: str,
    expected_info: os.stat_result | None = None,
) -> str:
    """Reconstruct the Git tree from one held, exact gzip member."""
    owned_descriptor = -1
    if isinstance(source, int):
        descriptor = source
        before = os.fstat(descriptor)
        if expected_info is not None and _file_identity(before) != _file_identity(
            expected_info
        ):
            raise AuthorityError("source archive descriptor identity differs")
    else:
        if not source.is_absolute():
            raise AuthorityError("source archive path must be absolute")
        owned_descriptor = os.open(
            source,
            os.O_RDONLY | getattr(os, "O_CLOEXEC", 0) | getattr(os, "O_NOFOLLOW", 0),
        )
        descriptor = owned_descriptor
        before = os.fstat(descriptor)
    if (
        not stat.S_ISREG(before.st_mode)
        or before.st_uid != os.geteuid()
        or before.st_nlink != 1
        or stat.S_IMODE(before.st_mode) & 0o022
        or not 1 <= before.st_size <= MAX_ARCHIVE
    ):
        if owned_descriptor >= 0:
            os.close(owned_descriptor)
        raise AuthorityError("source archive descriptor is unsafe")
    expanded = _single_gzip_payload(descriptor, before)
    files: dict[tuple[str, ...], tuple[bytes, bytes]] = {}
    directories: set[tuple[str, ...]] = {()}
    seen_paths: set[tuple[str, ...]] = set()
    total = 0
    try:
        with tarfile.open(fileobj=expanded, mode="r:") as archive:
            if archive.pax_headers != {"comment": source_ref}:
                raise AuthorityError("source archive Git commit marker differs")
            member_count = 0
            for member in archive:
                member_count += 1
                if member_count > MAX_ARCHIVE_MEMBERS:
                    raise AuthorityError("source archive member count differs")
                pure = PurePosixPath(member.name)
                parts = pure.parts
                try:
                    name_raw = member.name.encode("utf-8", errors="strict")
                except UnicodeEncodeError as error:
                    raise AuthorityError("source archive path is invalid") from error
                if (
                    not parts
                    or len(parts) > MAX_ARCHIVE_DEPTH
                    or len(name_raw) > MAX_ARCHIVE_PATH_BYTES
                    or pure.is_absolute()
                    or any(part in {"", ".", ".."} for part in parts)
                    or member.name != pure.as_posix()
                    or "\x00" in member.name
                ):
                    raise AuthorityError("source archive path is unsafe")
                key = tuple(parts)
                if key in seen_paths:
                    raise AuthorityError("source archive contains duplicate paths")
                seen_paths.add(key)
                if member.isdir():
                    if member.mode != 0o775 or key in files:
                        raise AuthorityError("source archive directory mode differs")
                    directories.add(key)
                    continue
                for offset in range(1, len(parts)):
                    parent = tuple(parts[:offset])
                    if parent in files:
                        raise AuthorityError(
                            "source archive path collides with a parent file"
                        )
                    directories.add(parent)
                if key in files or key in directories:
                    raise AuthorityError("source archive contains duplicate paths")
                if member.isfile():
                    if (
                        member.mode not in {0o664, 0o775}
                        or member.size < 0
                        or member.size > MAX_EXPANDED_ARCHIVE - total
                    ):
                        raise AuthorityError("source archive file mode/size differs")
                    stream = archive.extractfile(member)
                    if stream is None:
                        raise AuthorityError("source archive file payload is absent")
                    oid = _git_stream_blob_sha(stream, size=member.size)
                    payload_size = member.size
                    mode = b"100755" if member.mode == 0o775 else b"100644"
                elif member.issym():
                    if member.mode != 0o777 or member.size != 0:
                        raise AuthorityError("source archive symlink mode differs")
                    try:
                        raw = member.linkname.encode("utf-8", errors="strict")
                    except UnicodeEncodeError as error:
                        raise AuthorityError(
                            "source archive symlink target is invalid"
                        ) from error
                    if not raw or len(raw) > 4096 or b"\0" in raw:
                        raise AuthorityError("source archive symlink target is invalid")
                    oid = _git_object_sha(b"blob", raw)
                    payload_size = len(raw)
                    mode = b"120000"
                else:
                    raise AuthorityError("source archive member type is forbidden")
                total += payload_size
                if total > MAX_EXPANDED_ARCHIVE:
                    raise AuthorityError("source archive expanded size exceeds bound")
                files[key] = (mode, oid)
            if member_count == 0:
                raise AuthorityError("source archive member count differs")
    except (tarfile.TarError, OSError, EOFError) as error:
        raise AuthorityError(
            "source archive is not a valid bounded git tarball"
        ) from error
    finally:
        expanded.close()
        after = os.fstat(descriptor)
        if owned_descriptor >= 0:
            os.close(owned_descriptor)
        if _file_identity(before) != _file_identity(after):
            raise AuthorityError("source archive changed during validation")

    def tree(prefix: tuple[str, ...]) -> bytes:
        children: list[tuple[bytes, bool, bytes, bytes]] = []
        depth = len(prefix)
        direct_directories = {
            item
            for item in directories
            if len(item) == depth + 1 and item[:depth] == prefix
        }
        direct_files = {
            item: value
            for item, value in files.items()
            if len(item) == depth + 1 and item[:depth] == prefix
        }
        for item in direct_directories:
            name = item[-1].encode("utf-8", errors="strict")
            children.append((name, True, b"40000", tree(item)))
        for item, (mode, oid) in direct_files.items():
            name = item[-1].encode("utf-8", errors="strict")
            children.append((name, False, mode, oid))
        payload = b"".join(
            mode + b" " + name + b"\0" + oid
            for name, _directory, mode, oid in sorted(
                children, key=lambda row: row[0] + (b"/" if row[1] else b"")
            )
        )
        return _git_object_sha(b"tree", payload)

    return tree(()).hex()


def _source_object(
    gcloud: Path,
    env: dict[str, str],
    source_ref: str,
    *,
    source_tree_sha: str,
) -> tuple[dict[str, Any], str, int]:
    name = f"deploy-artifacts/{source_ref}/repo.tar.gz"
    uri = f"gs://{SOURCE_BUCKET}/{name}"
    value, query = _gcloud(
        gcloud,
        env,
        ["storage", "objects", "describe", uri, "--raw"],
        "GCS object metadata",
        projection=(
            "json(bucket,contentType,crc32c,etag,generation,id,kind,md5Hash,"
            "mediaLink,metageneration,name,selfLink,size,storageClass,timeCreated,"
            "timeStorageClassUpdated,updated,metadata)"
        ),
    )
    required_object_keys = {
        "bucket",
        "contentType",
        "crc32c",
        "etag",
        "generation",
        "id",
        "kind",
        "md5Hash",
        "mediaLink",
        "metageneration",
        "name",
        "selfLink",
        "size",
        "storageClass",
        "timeCreated",
        "timeStorageClassUpdated",
        "updated",
    }
    if not isinstance(value, dict) or set(value) not in {
        frozenset(required_object_keys),
        frozenset(required_object_keys | {"metadata"}),
    }:
        raise AuthorityError("GCS source object schema differs")
    custom_sha: str | None = None
    if "metadata" in value:
        metadata = _exact(value["metadata"], {"sha256"}, "GCS custom metadata")
        if (
            not isinstance(metadata["sha256"], str)
            or SHA256.fullmatch(metadata["sha256"]) is None
        ):
            raise AuthorityError("GCS custom SHA-256 is invalid")
        custom_sha = metadata["sha256"]
    generation = str(value["generation"])
    crc32c = _base64_hash(value["crc32c"], 4, "GCS CRC32C")
    md5_hash = _base64_hash(value["md5Hash"], 16, "GCS MD5")
    if (
        value["bucket"] != SOURCE_BUCKET
        or value["name"] != name
        or VERSION.fullmatch(generation) is None
        or not isinstance(value["size"], str)
        or not value["size"].isdigit()
        or not 1 <= int(value["size"]) <= MAX_ARCHIVE
        or not isinstance(value["metageneration"], str)
        or VERSION.fullmatch(value["metageneration"]) is None
        or not isinstance(value["storageClass"], str)
        or value["storageClass"] not in {"STANDARD", "NEARLINE", "COLDLINE", "ARCHIVE"}
        or not isinstance(value["updated"], str)
        or len(value["updated"]) > 64
    ):
        raise AuthorityError("GCS source identity differs")
    with tempfile.TemporaryDirectory(prefix="omega-release-authority-") as directory:
        target = Path(directory) / "source.tar.gz"
        _run(
            [
                str(Path(env.get("OMEGA_SEALED_PYTHON", str(GCLOUD_PYTHON)))),
                "-I",
                "-S",
                "-B",
                str(gcloud),
                "storage",
                "cp",
                "--quiet",
                "--no-clobber",
                f"{uri}#{generation}",
                str(target),
                "--project",
                PROJECT,
            ],
            env=env,
            timeout=600,
            maximum=4096,
        )
        target = target.resolve(strict=True)
        descriptor = os.open(
            target,
            os.O_RDONLY | getattr(os, "O_CLOEXEC", 0) | getattr(os, "O_NOFOLLOW", 0),
        )
        try:
            downloaded_info = os.fstat(descriptor)
            downloaded_sha, downloaded_md5 = _hash_descriptor(
                descriptor, downloaded_info, MAX_ARCHIVE
            )
            if (
                downloaded_info.st_size != int(value["size"])
                or downloaded_md5 != md5_hash
                or (custom_sha is not None and downloaded_sha != custom_sha)
            ):
                raise AuthorityError(
                    "generation-bound GCS download differs from metadata"
                )
            if SHA.fullmatch(source_tree_sha) is None:
                raise AuthorityError("reviewed source Git tree identity is invalid")
            archive_tree_sha = _archive_tree_sha(
                descriptor,
                source_ref=source_ref,
            )
            if archive_tree_sha != source_tree_sha:
                raise AuthorityError(
                    "generation-bound GCS archive differs from Git tree"
                )
        finally:
            os.close(descriptor)
    again, again_query = _gcloud(
        gcloud,
        env,
        ["storage", "objects", "describe", uri, "--raw"],
        "GCS object metadata readback",
        projection=(
            "json(bucket,contentType,crc32c,etag,generation,id,kind,md5Hash,"
            "mediaLink,metageneration,name,selfLink,size,storageClass,timeCreated,"
            "timeStorageClassUpdated,updated,metadata)"
        ),
    )
    if again != value:
        raise AuthorityError("GCS object mutated during authority generation")
    return (
        {
            "bucket": SOURCE_BUCKET,
            "crc32c": crc32c,
            "custom_metadata_sha256": custom_sha,
            "generation": generation,
            "git_tree_sha": archive_tree_sha,
            "md5_hash": md5_hash,
            "metageneration": str(value["metageneration"]),
            "name": name,
            "query_sha256": _sha((query + again_query).encode()),
            "sha256": downloaded_sha,
            "sha256_source": (
                "gcs-custom-metadata+generation-bound-download"
                if custom_sha is not None
                else "generation-bound-download"
            ),
            "size": int(value["size"]),
            "storage_class": value["storageClass"],
            "updated": value["updated"],
        },
        generation,
        int(value["size"]),
    )


def _live_vm(gcloud: Path, env: dict[str, str], boot_image: str) -> dict[str, Any]:
    value, query = _gcloud(
        gcloud,
        env,
        ["compute", "instances", "describe", INSTANCE, "--zone", ZONE],
        "live VM",
    )
    required = {
        "id",
        "name",
        "zone",
        "status",
        "metadata",
        "disks",
        "serviceAccounts",
        "labels",
        "tags",
    }
    if not isinstance(value, dict) or not required <= set(value):
        raise AuthorityError("live VM schema is incomplete")
    if (
        value["name"] != INSTANCE
        or str(value["zone"]).rsplit("/", 1)[-1] != ZONE
        or value["status"] != "RUNNING"
    ):
        raise AuthorityError("canonical writer VM identity differs")
    metadata = value["metadata"]
    if not isinstance(metadata, dict) or not isinstance(metadata.get("items"), list):
        raise AuthorityError("live VM metadata is incomplete")
    startup = [
        item
        for item in metadata["items"]
        if isinstance(item, dict)
        and item.get("key") == "startup-script"
        and set(item) == {"key", "value"}
    ]
    if len(startup) != 1 or not isinstance(startup[0]["value"], str):
        raise AuthorityError("live VM startup metadata is ambiguous")
    contracts = re.findall(
        r"(?m)^STARTUP_CONFIG_BASE64='([A-Za-z0-9+/=]+)'$",
        startup[0]["value"],
    )
    if len(contracts) == 1:
        try:
            startup_contract = _json(
                base64.b64decode(contracts[0], validate=True),
                "live startup contract",
                maximum=1024 * 1024,
            )
        except (ValueError, binascii.Error) as error:
            raise AuthorityError("live startup contract encoding is invalid") from error
        if (
            not isinstance(startup_contract, dict)
            or type(startup_contract.get("schema_version")) is not int
            or startup_contract["schema_version"] != 1
            or startup_contract.get("project_id") != PROJECT
            or startup_contract.get("environment") != "staging"
            or startup_contract.get("canonical_writer") is not True
            or startup_contract.get("enable_airflow_scheduler") is not True
            or not isinstance(startup_contract.get("controller_ref"), str)
            or SHA.fullmatch(startup_contract["controller_ref"]) is None
            or not isinstance(startup_contract.get("source"), dict)
            or not isinstance(startup_contract["source"].get("ref"), str)
            or SHA.fullmatch(startup_contract["source"]["ref"]) is None
        ):
            raise AuthorityError(
                "live startup does not prove the unique writer/scheduler role"
            )
        startup_controller_ref: str | None = startup_contract["controller_ref"]
        startup_source_ref = startup_contract["source"]["ref"]
        startup_contract_schema: int | str = 1
    elif not contracts:
        # The observed pre-foundation controller predates the JSON contract.
        # It is evidence of live identity only; release writer/scheduler inputs
        # remain fixed policy and are not inferred from these legacy bytes.
        legacy_refs = re.findall(
            r'(?m)^SOURCE_SHA="([0-9a-f]{40})"$', startup[0]["value"]
        )
        if len(legacy_refs) != 1:
            raise AuthorityError("live legacy startup source identity is ambiguous")
        startup_controller_ref = None
        startup_source_ref = legacy_refs[0]
        startup_contract_schema = "legacy-pre-foundation"
    else:
        raise AuthorityError("live startup scheduler authority is ambiguous")
    service_accounts = value["serviceAccounts"]
    if (
        not isinstance(service_accounts, list)
        or len(service_accounts) != 1
        or not isinstance(service_accounts[0], dict)
        or set(service_accounts[0]) != {"email", "scopes"}
        or service_accounts[0].get("email") != SERVICE_ACCOUNT
        or service_accounts[0].get("scopes")
        != ["https://www.googleapis.com/auth/cloud-platform"]
    ):
        raise AuthorityError("canonical writer service account differs")
    disks = value["disks"]
    if not isinstance(disks, list):
        raise AuthorityError("live VM disk inventory is invalid")
    boot = [
        item for item in disks if isinstance(item, dict) and item.get("boot") is True
    ]
    if len(boot) != 1 or not isinstance(boot[0].get("source"), str):
        raise AuthorityError("live VM boot disk is ambiguous")
    disk_name = boot[0]["source"].rsplit("/", 1)[-1]
    disk, disk_query = _gcloud(
        gcloud,
        env,
        ["compute", "disks", "describe", disk_name, "--zone", ZONE],
        "live boot disk",
    )
    if (
        not isinstance(disk, dict)
        or disk.get("sourceImage")
        != f"https://www.googleapis.com/compute/v1/{boot_image}"
    ):
        raise AuthorityError("live immutable boot image differs from package lock")
    instance_id = str(value["id"])
    if not instance_id.isdigit():
        raise AuthorityError("live VM instance ID is invalid")
    return {
        "boot_disk": disk_name,
        "boot_image": boot_image,
        "canonical_writer": True,
        "enable_airflow_scheduler": True,
        "instance_id": instance_id,
        "name": INSTANCE,
        "old_startup_sha256": _sha(startup[0]["value"].encode()),
        "project": PROJECT,
        "query_sha256": _sha((query + disk_query).encode()),
        "service_account": SERVICE_ACCOUNT,
        "startup_contract_schema": startup_contract_schema,
        "startup_controller_ref": startup_controller_ref,
        "startup_source_ref": startup_source_ref,
        "zone": ZONE,
    }


def _secret_versions(
    gcloud: Path, env: dict[str, str]
) -> tuple[dict[str, str], list[dict[str, Any]]]:
    selected: dict[str, str] = {}
    evidence: list[dict[str, Any]] = []
    for suffix in SECRET_NAMES:
        secret = f"omega-staging-{suffix}"
        value, query = _gcloud(
            gcloud,
            env,
            [
                "secrets",
                "versions",
                "list",
                secret,
                "--filter",
                "state=ENABLED",
                "--sort-by=name",
                "--limit=101",
            ],
            f"secret version metadata for {suffix}",
            projection="json(name,state,createTime,etag)",
        )
        if not isinstance(value, list) or not 1 <= len(value) <= 100:
            raise AuthorityError("secret version metadata is not a list")
        allowed = {"createTime", "etag", "name", "state"}
        versions: dict[int, dict[str, Any]] = {}
        prefix = f"projects/894064513501/secrets/{secret}/versions/"
        for item in value:
            if (
                not isinstance(item, dict)
                or set(item) != allowed
                or item["state"] != "ENABLED"
                or not isinstance(item["name"], str)
                or not item["name"].startswith(prefix)
            ):
                raise AuthorityError("secret version metadata schema differs")
            version = item["name"].removeprefix(prefix)
            if VERSION.fullmatch(version) is None or int(version) in versions:
                raise AuthorityError("secret version identity is invalid")
            versions[int(version)] = item
        version_number = max(versions)
        version = str(version_number)
        item = versions[version_number]
        selected[suffix] = version
        evidence.append(
            {
                "create_time": item["createTime"],
                "etag": item["etag"],
                "name": suffix,
                "query_sha256": query,
                "state": "ENABLED",
                "version": version,
            }
        )
    return selected, evidence


def _write_exclusive(path: Path, raw: bytes) -> None:
    resolved_parent = path.parent.resolve(strict=True) if path.is_absolute() else None
    if (
        not path.is_absolute()
        or path.parent.is_symlink()
        or resolved_parent != path.parent
        or (resolved_parent / path.name).is_relative_to(ROOT)
    ):
        raise AuthorityError("output path is unsafe")
    parent = os.open(
        path.parent, os.O_RDONLY | os.O_DIRECTORY | getattr(os, "O_NOFOLLOW", 0)
    )
    descriptor = -1
    created = False
    try:
        parent_info = os.fstat(parent)

        def revalidate_parent() -> None:
            current = os.stat(path.parent, follow_symlinks=False)
            if (
                not stat.S_ISDIR(parent_info.st_mode)
                or parent_info.st_uid != os.geteuid()
                or stat.S_IMODE(parent_info.st_mode) & 0o022
                or not stat.S_ISDIR(current.st_mode)
                or (current.st_dev, current.st_ino)
                != (parent_info.st_dev, parent_info.st_ino)
            ):
                raise AuthorityError("output parent ownership/mode differs")

        revalidate_parent()
        flags = os.O_WRONLY | os.O_CREAT | os.O_EXCL | getattr(os, "O_NOFOLLOW", 0)
        descriptor = os.open(path.name, flags, 0o400, dir_fd=parent)
        created = True
        offset = 0
        while offset < len(raw):
            written = os.write(descriptor, raw[offset:])
            if written <= 0:
                raise AuthorityError("authority write was incomplete")
            offset += written
        os.fsync(descriptor)
        info = os.fstat(descriptor)
        if (
            stat.S_IMODE(info.st_mode) != 0o400
            or info.st_uid != os.geteuid()
            or info.st_nlink != 1
            or info.st_size != len(raw)
        ):
            raise AuthorityError("authority output identity differs")
        os.close(descriptor)
        descriptor = -1
        os.fsync(parent)
        revalidate_parent()
        readback, _info = _read_regular(path, len(raw))
        if readback != raw:
            raise AuthorityError("authority readback differs")
        created = False
    except Exception:
        if created:
            try:
                os.unlink(path.name, dir_fd=parent)
                os.fsync(parent)
            except OSError:
                pass
        raise
    finally:
        if descriptor >= 0:
            os.close(descriptor)
        os.close(parent)


def _sha_value(value: Any, label: str, *, git: bool = False) -> str:
    pattern = SHA if git else SHA256
    if not isinstance(value, str) or pattern.fullmatch(value) is None:
        raise AuthorityError(f"{label} is invalid")
    return value


def _blob_value(value: Any, label: str) -> str:
    if (
        not isinstance(value, str)
        or re.fullmatch(r"[0-9a-f]{40}|[0-9a-f]{64}", value) is None
    ):
        raise AuthorityError(f"{label} is invalid")
    return value


def _positive_int(value: Any, label: str, *, maximum: int = 2**63 - 1) -> int:
    if (
        not isinstance(value, int)
        or isinstance(value, bool)
        or not 1 <= value <= maximum
    ):
        raise AuthorityError(f"{label} is invalid")
    return value


def _timestamp(value: Any, label: str) -> str:
    if (
        not isinstance(value, str)
        or re.fullmatch(
            r"20[0-9]{2}-[0-9]{2}-[0-9]{2}T[0-9]{2}:[0-9]{2}:[0-9]{2}"
            r"(?:[.][0-9]{1,9})?(?:Z|[+-][0-9]{2}:[0-9]{2})",
            value,
        )
        is None
    ):
        raise AuthorityError(f"{label} is invalid")
    return value


def validate_authority_receipt(value: Any) -> dict[str, Any]:
    """Validate the full closed v2 receipt without filesystem or network I/O."""
    top_keys = {
        "approved_main_sha",
        "boot_image",
        "canonical_writer",
        "certificate_manager_map_name",
        "controller_ref",
        "enable_airflow_scheduler",
        "evidence_chain_sha256",
        "foundation_predecessor",
        "host_package_versions",
        "lakehouse_bucket_name",
        "lakehouse_endpoint",
        "old_live_startup_sha256",
        "provenance",
        "public_console_domain",
        "public_workspace_domain",
        "schema_version",
        "secret_versions",
        "source_archive_sha256",
        "source_bucket",
        "source_generation",
        "source_object",
        "source_sha",
        "source_size_bytes",
    }
    authority = _exact(value, top_keys, "release authority")
    chain = _sha_value(authority["evidence_chain_sha256"], "evidence chain")
    without_chain = dict(authority)
    del without_chain["evidence_chain_sha256"]
    try:
        expected_chain = _sha(_canonical(without_chain))
    except (TypeError, ValueError) as error:
        raise AuthorityError("release authority is not canonical JSON") from error
    if chain != expected_chain:
        raise AuthorityError("release authority evidence chain differs")

    source_sha = _sha_value(authority["source_sha"], "source SHA", git=True)
    controller_ref = _sha_value(authority["controller_ref"], "controller ref", git=True)
    source_archive_sha = _sha_value(
        authority["source_archive_sha256"], "source archive SHA-256"
    )
    old_startup_sha = _sha_value(
        authority["old_live_startup_sha256"], "old startup SHA-256"
    )
    if (
        type(authority["schema_version"]) is not int
        or authority["schema_version"] != 2
        or authority["approved_main_sha"] != source_sha
        or authority["canonical_writer"] is not True
        or authority["enable_airflow_scheduler"] is not True
        or authority["foundation_predecessor"] is not None
        or authority["certificate_manager_map_name"] != "sevenbs-production-map"
        or authority["lakehouse_bucket_name"] != ""
        or authority["lakehouse_endpoint"] != "storage.googleapis.com"
        or authority["public_console_domain"] != "console.7businesssolutions.com"
        or authority["public_workspace_domain"] != "workspace.7businesssolutions.com"
        or authority["source_bucket"] != SOURCE_BUCKET
        or authority["source_object"] != f"deploy-artifacts/{source_sha}/repo.tar.gz"
        or not isinstance(authority["source_generation"], str)
        or VERSION.fullmatch(authority["source_generation"]) is None
        or not isinstance(authority["source_size_bytes"], int)
        or isinstance(authority["source_size_bytes"], bool)
        or not 1 <= authority["source_size_bytes"] <= MAX_ARCHIVE
        or not isinstance(authority["boot_image"], str)
        or BOOT_IMAGE.fullmatch(authority["boot_image"]) is None
    ):
        raise AuthorityError("release authority policy inputs differ")

    packages = _exact(
        authority["host_package_versions"], set(PACKAGE_NAMES), "package inventory"
    )
    if any(
        not isinstance(version, str) or PACKAGE_VERSION.fullmatch(version) is None
        for version in packages.values()
    ):
        raise AuthorityError("release authority package version is invalid")
    secrets = _exact(
        authority["secret_versions"], set(SECRET_NAMES), "secret-version inventory"
    )
    if any(
        not isinstance(version, str) or VERSION.fullmatch(version) is None
        for version in secrets.values()
    ):
        raise AuthorityError("release authority secret version is invalid")

    provenance = _exact(
        authority["provenance"],
        {
            "generator",
            "git",
            "github",
            "live_vm",
            "package_lock",
            "secret_versions",
            "source_object",
            "tools",
        },
        "release provenance",
    )
    generator = _exact(
        provenance["generator"],
        {"content_sha256", "git_blob_id", "path"},
        "generator provenance",
    )
    _sha_value(generator["content_sha256"], "generator content SHA-256")
    _blob_value(generator["git_blob_id"], "generator Git blob")
    if generator["path"] != GENERATOR:
        raise AuthorityError("generator path differs")

    git = _exact(
        provenance["git"],
        {"controller_ref", "main_ref", "main_sha", "repository", "source_tree_sha"},
        "Git provenance",
    )
    _sha_value(git["source_tree_sha"], "source tree SHA", git=True)
    if git != {
        "controller_ref": controller_ref,
        "main_ref": "refs/heads/main",
        "main_sha": source_sha,
        "repository": REPOSITORY,
        "source_tree_sha": git["source_tree_sha"],
    }:
        raise AuthorityError("Git provenance identity differs")

    github = _exact(
        provenance["github"],
        {"checks", "commit_url", "main_ref", "main_sha", "query_sha256", "repository"},
        "GitHub provenance",
    )
    _sha_value(github["query_sha256"], "GitHub query SHA-256")
    if (
        github["repository"] != REPOSITORY
        or github["main_ref"] != "refs/heads/main"
        or github["main_sha"] != source_sha
        or github["commit_url"]
        != f"https://github.com/{REPOSITORY}/commit/{source_sha}"
        or not isinstance(github["checks"], list)
        or len(github["checks"]) != len(REQUIRED_CHECKS)
    ):
        raise AuthorityError("GitHub provenance identity differs")
    for check, expected_name in zip(github["checks"], REQUIRED_CHECKS):
        check = _exact(
            check,
            {
                "conclusion",
                "gate_job",
                "gate_job_id",
                "head_sha",
                "name",
                "query_sha256",
                "run_attempt",
                "status",
                "workflow_path",
                "workflow_run_id",
            },
            "GitHub check provenance",
        )
        path, gate = WORKFLOWS[expected_name]
        _positive_int(check["gate_job_id"], "GitHub gate-job ID")
        _positive_int(check["workflow_run_id"], "GitHub workflow-run ID")
        _sha_value(check["query_sha256"], "GitHub gate query SHA-256")
        if (
            check
            != {
                "conclusion": "success",
                "gate_job": gate,
                "gate_job_id": check["gate_job_id"],
                "head_sha": source_sha,
                "name": expected_name,
                "query_sha256": check["query_sha256"],
                "run_attempt": 1,
                "status": "completed",
                "workflow_path": path,
                "workflow_run_id": check["workflow_run_id"],
            }
            or type(check["run_attempt"]) is not int
        ):
            raise AuthorityError("GitHub required check identity differs")

    live = _exact(
        provenance["live_vm"],
        {
            "boot_disk",
            "boot_image",
            "canonical_writer",
            "enable_airflow_scheduler",
            "instance_id",
            "name",
            "old_startup_sha256",
            "project",
            "query_sha256",
            "service_account",
            "startup_contract_schema",
            "startup_controller_ref",
            "startup_source_ref",
            "zone",
        },
        "live VM provenance",
    )
    _sha_value(live["query_sha256"], "live VM query SHA-256")
    _sha_value(live["startup_source_ref"], "live startup source ref", git=True)
    if (
        not isinstance(live["boot_disk"], str)
        or re.fullmatch(r"[a-z](?:[-a-z0-9]{0,61}[a-z0-9])?", live["boot_disk"]) is None
        or not isinstance(live["instance_id"], str)
        or re.fullmatch(r"[1-9][0-9]{0,19}", live["instance_id"]) is None
        or live["boot_image"] != authority["boot_image"]
        or live["canonical_writer"] is not True
        or live["enable_airflow_scheduler"] is not True
        or live["name"] != INSTANCE
        or live["old_startup_sha256"] != old_startup_sha
        or live["project"] != PROJECT
        or live["service_account"] != SERVICE_ACCOUNT
        or live["zone"] != ZONE
    ):
        raise AuthorityError("live VM provenance identity differs")
    if (
        type(live["startup_contract_schema"]) is int
        and live["startup_contract_schema"] == 1
    ):
        _sha_value(
            live["startup_controller_ref"], "live startup controller ref", git=True
        )
    elif (
        live["startup_contract_schema"] != "legacy-pre-foundation"
        or live["startup_controller_ref"] is not None
    ):
        raise AuthorityError("live startup contract provenance differs")

    lock = _exact(
        provenance["package_lock"],
        {"content_sha256", "git_blob_id", "path", "schema_version"},
        "package-lock provenance",
    )
    _sha_value(lock["content_sha256"], "package-lock SHA-256")
    _blob_value(lock["git_blob_id"], "package-lock Git blob")
    if (
        lock["path"] != PACKAGE_LOCK
        or type(lock["schema_version"]) is not int
        or lock["schema_version"] != 1
    ):
        raise AuthorityError("package-lock provenance differs")

    version_evidence = provenance["secret_versions"]
    if not isinstance(version_evidence, list) or len(version_evidence) != len(
        SECRET_NAMES
    ):
        raise AuthorityError("secret-version evidence inventory differs")
    for evidence, name in zip(version_evidence, SECRET_NAMES):
        evidence = _exact(
            evidence,
            {"create_time", "etag", "name", "query_sha256", "state", "version"},
            "secret-version provenance",
        )
        _timestamp(evidence["create_time"], "secret-version create time")
        _sha_value(evidence["query_sha256"], "secret-version query SHA-256")
        if (
            not isinstance(evidence["etag"], str)
            or not 1 <= len(evidence["etag"]) <= 256
            or re.fullmatch(r"[ -~]+", evidence["etag"]) is None
            or evidence["name"] != name
            or evidence["state"] != "ENABLED"
            or evidence["version"] != secrets[name]
        ):
            raise AuthorityError("secret-version provenance identity differs")

    source = _exact(
        provenance["source_object"],
        {
            "bucket",
            "crc32c",
            "custom_metadata_sha256",
            "generation",
            "git_tree_sha",
            "md5_hash",
            "metageneration",
            "name",
            "query_sha256",
            "sha256",
            "sha256_source",
            "size",
            "storage_class",
            "updated",
        },
        "source-object provenance",
    )
    _base64_hash(source["crc32c"], 4, "source-object CRC32C")
    _base64_hash(source["md5_hash"], 16, "source-object MD5")
    _sha_value(source["query_sha256"], "source-object query SHA-256")
    _sha_value(source["git_tree_sha"], "source-object Git tree", git=True)
    _timestamp(source["updated"], "source-object update time")
    _positive_int(source["size"], "source-object size", maximum=MAX_ARCHIVE)
    custom = source["custom_metadata_sha256"]
    if custom is not None:
        _sha_value(custom, "source-object custom SHA-256")
    expected_source = (
        "gcs-custom-metadata+generation-bound-download"
        if custom is not None
        else "generation-bound-download"
    )
    if (
        source["bucket"] != SOURCE_BUCKET
        or source["generation"] != authority["source_generation"]
        or source["git_tree_sha"] != git["source_tree_sha"]
        or source["name"] != authority["source_object"]
        or source["sha256"] != source_archive_sha
        or (custom is not None and custom != source_archive_sha)
        or source["sha256_source"] != expected_source
        or source["size"] != authority["source_size_bytes"]
        or not isinstance(source["metageneration"], str)
        or VERSION.fullmatch(source["metageneration"]) is None
        or not isinstance(source["storage_class"], str)
        or source["storage_class"]
        not in {"STANDARD", "NEARLINE", "COLDLINE", "ARCHIVE"}
    ):
        raise AuthorityError("source-object provenance identity differs")

    tools = _exact(provenance["tools"], {"gcloud", "gh"}, "tool provenance")
    for key, label in (("gh", "GitHub CLI"), ("gcloud", "gcloud CLI")):
        tool = _exact(
            tools[key], {"content_sha256", "path", "size"}, f"{label} provenance"
        )
        _positive_int(tool["size"], f"{label} size", maximum=128 * 1024 * 1024)
        if (
            tool["content_sha256"] != TOOL_HASHES[label]
            or tool["path"] != TOOL_PATHS[label]
        ):
            raise AuthorityError(f"{label} provenance differs")

    try:
        normalized = json.loads(_canonical(authority), object_pairs_hook=_pairs)
    except (TypeError, ValueError, json.JSONDecodeError) as error:
        raise AuthorityError("release authority cannot be normalized") from error
    if not isinstance(normalized, dict):
        raise AuthorityError("release authority cannot be normalized")
    return normalized


def _build(
    args: argparse.Namespace, *, runtime: dict[str, Any] | None = None
) -> dict[str, Any]:
    if runtime is None:
        with _sealed_execution_runtime(
            args.gh_config, args.gcloud_config
        ) as sealed_runtime:
            return _build(args, runtime=sealed_runtime)
    if (
        SHA.fullmatch(args.source_ref) is None
        or SHA.fullmatch(args.controller_ref) is None
    ):
        raise AuthorityError("source/controller refs must be full SHAs")
    git = _clean_git(args.source_ref, args.controller_ref)
    generator_raw, generator_blob = _git_blob(
        args.controller_ref, GENERATOR, maximum=512 * 1024
    )
    running_generator, _generator_info = _read_regular(
        (ROOT / GENERATOR).resolve(), 512 * 1024
    )
    if running_generator != generator_raw:
        raise AuthorityError("running generator differs from controller commit")
    boot_image, packages, package_lock = _package_lock(args.controller_ref)
    gh = runtime["gh"]
    gh_identity = runtime["gh_identity"]
    gcloud = runtime["gcloud"]
    gcloud_identity = runtime["gcloud_identity"]
    private_gh_config = runtime["gh_config"]
    private_gcloud_config = runtime["gcloud_config"]
    if runtime.get("gcloud_sdk_identity", {}).get("sha256") != GCLOUD_SDK_TREE_SHA256:
        raise AuthorityError("gcloud SDK execution snapshot differs")
    if runtime.get("python_identity", {}).get("sha256") != PYTHON_RUNTIME_TREE_SHA256:
        raise AuthorityError("Python execution snapshot differs")
    github = _github(gh, private_gh_config, args.source_ref)
    environment = _gcloud_env(
        private_gcloud_config,
        python=Path(runtime["python"]),
        python_framework=Path(runtime["python_framework"]),
    )
    source, generation, size = _source_object(
        gcloud,
        environment,
        args.source_ref,
        source_tree_sha=git["source_tree_sha"],
    )
    live_vm = _live_vm(gcloud, environment, boot_image)
    secret_versions, secret_evidence = _secret_versions(gcloud, environment)
    # Bracket the mutable live inputs after the generation-bound object proof.
    # The final GitHub read is deliberately last so main cannot move during the
    # slower GCP evidence collection without invalidating this generation.
    if _live_vm(gcloud, environment, boot_image) != live_vm:
        raise AuthorityError("live VM changed during authority generation")
    if _secret_versions(gcloud, environment) != (
        secret_versions,
        secret_evidence,
    ):
        raise AuthorityError("secret versions changed during authority generation")
    if _github(gh, private_gh_config, args.source_ref) != github:
        raise AuthorityError("GitHub evidence changed during authority generation")
    authority: dict[str, Any] = {
        "approved_main_sha": args.source_ref,
        "boot_image": boot_image,
        "canonical_writer": True,
        "certificate_manager_map_name": "sevenbs-production-map",
        "controller_ref": args.controller_ref,
        "enable_airflow_scheduler": True,
        "foundation_predecessor": None,
        "host_package_versions": packages,
        "lakehouse_bucket_name": "",
        "lakehouse_endpoint": "storage.googleapis.com",
        "old_live_startup_sha256": live_vm["old_startup_sha256"],
        "provenance": {
            "generator": {
                "content_sha256": _sha(generator_raw),
                "git_blob_id": generator_blob,
                "path": GENERATOR,
            },
            "git": git,
            "github": github,
            "live_vm": live_vm,
            "package_lock": package_lock,
            "secret_versions": secret_evidence,
            "source_object": source,
            "tools": {"gcloud": gcloud_identity, "gh": gh_identity},
        },
        "public_console_domain": "console.7businesssolutions.com",
        "public_workspace_domain": "workspace.7businesssolutions.com",
        "schema_version": 2,
        "secret_versions": secret_versions,
        "source_archive_sha256": source["sha256"],
        "source_bucket": SOURCE_BUCKET,
        "source_generation": generation,
        "source_object": source["name"],
        "source_sha": args.source_ref,
        "source_size_bytes": size,
    }
    authority["evidence_chain_sha256"] = _sha(_canonical(authority))
    return validate_authority_receipt(authority)


def generate(args: argparse.Namespace) -> dict[str, Any]:
    authority = _build(args)
    _write_exclusive(args.output, _canonical(authority))
    return authority


def verify(args: argparse.Namespace) -> dict[str, Any]:
    raw, info = _read_regular(args.authority, 2 * 1024 * 1024)
    if stat.S_IMODE(info.st_mode) != 0o400:
        raise AuthorityError("release authority must be mode 0400")
    supplied = validate_authority_receipt(
        _json(raw, "release authority", maximum=2 * 1024 * 1024)
    )
    if raw != _canonical(supplied):
        raise AuthorityError("release authority bytes are not canonical")
    args.source_ref = supplied["source_sha"]
    args.controller_ref = supplied["controller_ref"]
    expected = _build(args)
    if supplied != expected:
        raise AuthorityError("release authority differs from current exact evidence")
    return supplied


def _parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description=__doc__)
    actions = parser.add_subparsers(dest="action", required=True)
    generate_parser = actions.add_parser("generate")
    generate_parser.add_argument("--output", type=Path, required=True)
    generate_parser.add_argument("--source-ref", required=True)
    generate_parser.add_argument("--controller-ref", required=True)
    verify_parser = actions.add_parser("verify")
    verify_parser.add_argument("--authority", type=Path, required=True)
    for action in (generate_parser, verify_parser):
        action.add_argument("--gh-config", type=Path, required=True)
        action.add_argument("--gcloud-config", type=Path, required=True)
    return parser


def main() -> int:
    try:
        args = _parser().parse_args()
        (generate if args.action == "generate" else verify)(args)
    except (
        AuthorityError,
        OSError,
        UnicodeError,
        ValueError,
        TypeError,
        KeyError,
        AttributeError,
        IndexError,
        binascii.Error,
    ) as error:
        print(f"release authority failed closed: {error}", file=os.sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
