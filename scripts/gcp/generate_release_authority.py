def _private_gh_config(source: Path, destination: Path) -> dict[str, str]:
    source = _config_dir(source, "GitHub CLI")
    if source.name != "gh" or source.parent.name != ".config":
        raise AuthorityError("GitHub CLI config must be the explicit home config")
    hosts_raw, _hosts_info = _read_regular(
        (source / "hosts.yml").resolve(strict=True), 64 * 1024
    )
    try:
        hosts_text = hosts_raw.decode("utf-8", errors="strict")
    except UnicodeDecodeError as error:
        raise AuthorityError("GitHub CLI host config is not UTF-8") from error
    forbidden = re.compile(
        r"(?i)(?:http_unix_socket|https?_proxy|all_proxy|proxy_url|"
        r"unix_socket|https?://|api[_-]?endpoint|!include|&[A-Za-z]|\*[A-Za-z])"
    )
    if forbidden.search(hosts_text):
        raise AuthorityError("GitHub CLI host config contains a transport override")
    allowed_lines = {
        "github.com:",
        "    git_protocol: https",
        "    users:",
        f"        {GITHUB_ACCOUNT}:",
        f"    user: {GITHUB_ACCOUNT}",
    }
    lines = [line for line in hosts_text.splitlines() if line]
    token_lines = [
        line for line in lines if re.fullmatch(r"    oauth_token: [^\s]{20,8192}", line)
    ]
    if (
        any(line not in allowed_lines and line not in token_lines for line in lines)
        or {line for line in lines if line not in token_lines} != allowed_lines
        or len(token_lines) > 1
    ):
        raise AuthorityError("GitHub CLI host config schema differs")
    home = destination / "home"
    config = home / ".config" / "gh"
    config.mkdir(parents=True, mode=0o700)
    private_global = (
        b"version: 1\n"
        b"git_protocol: https\n"
        b"editor:\n"
        b"prompt: disabled\n"
        b"prefer_editor_prompt: disabled\n"
        b"pager:\n"
        b"aliases:\n"
        b"http_unix_socket:\n"
        b"browser:\n"
        b"color_labels: disabled\n"
        b"accessible_colors: disabled\n"
        b"accessible_prompter: disabled\n"
        b"spinner: disabled\n"
    )
    _write_private_file(config / "config.yml", private_global, 0o600)
    _write_private_file(config / "hosts.yml", hosts_raw, 0o600)
    return {"host": "github.com", "user": GITHUB_ACCOUNT}


