def _private_python_canary(python: Path, framework: Path) -> dict[str, Any]:
    """Prove that Python and its native dependency closure load privately."""
    script = r"""
import _sqlite3
import _ssl
import ctypes
import json
import sqlite3
import ssl
import sys
import sysconfig

dyld = ctypes.CDLL(None)
dyld._dyld_image_count.argtypes = []
dyld._dyld_image_count.restype = ctypes.c_uint32
dyld._dyld_get_image_name.argtypes = [ctypes.c_uint32]
dyld._dyld_get_image_name.restype = ctypes.c_char_p
images = []
for index in range(dyld._dyld_image_count()):
    value = dyld._dyld_get_image_name(index)
    if value:
        images.append(value.decode("utf-8", errors="strict"))
print(json.dumps({
    "base_prefix": sys.base_prefix,
    "executable": sys.executable,
    "images": sorted(set(images)),
    "origins": {
        "_sqlite3": _sqlite3.__file__,
        "_ssl": _ssl.__file__,
        "sqlite3": sqlite3.__file__,
        "ssl": ssl.__file__,
        "sysconfig": sysconfig.__file__,
    },
    "openssl": ssl.OPENSSL_VERSION,
    "path": sys.path,
    "prefix": sys.prefix,
    "version": list(sys.version_info[:3]),
}, sort_keys=True, separators=(",", ":")))
"""
    environment = {
        "HOME": "/var/empty",
        "LANG": "C.UTF-8",
        "LC_ALL": "C.UTF-8",
        "PATH": "/usr/bin:/bin",
        **_python_runtime_environment(python, framework),
    }
    raw = _run(
        [str(python), "-I", "-S", "-B", "-c", script],
        cwd=framework,
        env=environment,
        timeout=30,
        maximum=512 * 1024,
    )
    value = _json(raw, "private Python runtime canary", maximum=512 * 1024)
    if not isinstance(value, dict) or set(value) != {
        "base_prefix",
        "executable",
        "images",
        "origins",
        "openssl",
        "path",
        "prefix",
        "version",
    }:
        raise AuthorityError("private Python runtime canary schema differs")
    version_root = (framework / "Versions" / PYTHON_RUNTIME_VERSION).resolve()

    def inside_runtime(raw_path: Any) -> bool:
        if not isinstance(raw_path, str) or not raw_path.startswith("/"):
            return False
        try:
            Path(raw_path).resolve(strict=False).relative_to(version_root)
        except ValueError:
            return False
        return True

    if (
        value["version"] != [3, 14, 5]
        or Path(value["executable"]).resolve(strict=True) != python.resolve(strict=True)
        or any(
            Path(value[name]).resolve(strict=True) != version_root
            for name in ("prefix", "base_prefix")
        )
        or not isinstance(value["path"], list)
        or not value["path"]
        or any(not inside_runtime(item) for item in value["path"])
        or not isinstance(value["origins"], dict)
        or set(value["origins"]) != {"_sqlite3", "_ssl", "sqlite3", "ssl", "sysconfig"}
        or any(not inside_runtime(item) for item in value["origins"].values())
        or not isinstance(value["openssl"], str)
        or not value["openssl"].startswith("OpenSSL 3.")
        or not isinstance(value["images"], list)
    ):
        raise AuthorityError("private Python runtime escaped its sealed framework")
    private_images = [
        item
        for item in value["images"]
        if isinstance(item, str)
        and not item.startswith(("/System/Library/", "/usr/lib/"))
    ]
    if not private_images or any(not inside_runtime(item) for item in private_images):
        raise AuthorityError("private Python native library origin differs")
    required_images = {
        str(version_root / "Python"),
        str(version_root / "lib/libcrypto.3.dylib"),
        str(version_root / "lib/libssl.3.dylib"),
    }
    if not required_images.issubset(set(value["images"])):
        raise AuthorityError("private Python native dependency closure differs")
    return value


