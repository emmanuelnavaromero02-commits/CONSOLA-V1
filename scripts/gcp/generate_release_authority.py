class AuthorityError(RuntimeError):
    """Release authority cannot be proved exactly."""


def _file_identity(value: os.stat_result) -> tuple[int, int, int, int, int]:
    return (
        value.st_dev,
        value.st_ino,
        value.st_size,
        value.st_mtime_ns,
        value.st_ctime_ns,
    )


def _write_private_file(path: Path, raw: bytes, mode: int) -> None:
    descriptor = os.open(
        path,
        os.O_WRONLY
        | os.O_CREAT
        | os.O_EXCL
        | getattr(os, "O_CLOEXEC", 0)
        | getattr(os, "O_NOFOLLOW", 0),
        mode,
    )
    try:
        view = memoryview(raw)
        while view:
            written = os.write(descriptor, view)
            if written <= 0:
                raise AuthorityError("private runtime copy made no progress")
            view = view[written:]
        os.fchmod(descriptor, mode)
        os.fsync(descriptor)
        info = os.fstat(descriptor)
        if (
            not stat.S_ISREG(info.st_mode)
            or info.st_uid != os.geteuid()
            or info.st_nlink != 1
            or stat.S_IMODE(info.st_mode) != mode
            or info.st_size != len(raw)
        ):
            raise AuthorityError("private runtime copy identity differs")
    finally:
        os.close(descriptor)


def _remove_private_tree(root: Path) -> None:
    """Remove one exact process-owned temporary tree, including broken links."""
    # Python 3.9's TemporaryDirectory cleanup can strand broken framework
    # symlinks on macOS.  Walk bottom-up without following links so credential
    # projections are not retained after either success or failure.
    for directory, names, files in os.walk(root, topdown=False, followlinks=False):
        current = Path(directory)
        current.chmod(0o700)
        for name in files:
            (current / name).unlink()
        for name in names:
            child = current / name
            if child.is_symlink():
                child.unlink()
            else:
                child.chmod(0o700)
                child.rmdir()
    root.rmdir()


@contextlib.contextmanager
def _private_temporary_directory(prefix: str) -> Iterator[Path]:
    root = Path(tempfile.mkdtemp(prefix=prefix, dir="/tmp"))
    root.chmod(0o700)
    try:
        yield root
    finally:
        _remove_private_tree(root)


def _normalized_link(prefix: tuple[str, ...], target: str) -> tuple[str, ...] | None:
    if not target or target.startswith("/") or "\x00" in target:
        raise AuthorityError("runtime tree symlink target is unsafe")
    result = list(prefix)
    for part in PurePosixPath(target).parts:
        if part in {"", "."}:
            continue
        if part == "..":
            if not result:
                return None
            result.pop()
        else:
            result.append(part)
    return tuple(result)


def _runtime_tree_snapshot(
    source: Path,
    destination: Path | None,
    *,
    expected_sha256: str | None = None,
    allow_writable_source: bool = False,
    omit_python_bytecode: bool = False,
) -> dict[str, int | str]:
    """Copy/attest one closed runtime tree using held directory/file FDs.

    Cloud SDK archives intentionally contain source, not interpreter-specific
    bytecode.  A locally installed SDK may accumulate ``__pycache__`` entries;
    those are neither release inputs nor safe to execute after another Python
    runtime created them.  The SDK projection therefore omits them and is run
    with ``-B``.  Other runtime trees remain byte-for-byte complete.
    """
    if allow_writable_source and expected_sha256 is None:
        raise AuthorityError("writable runtime source requires a reviewed digest")
    source = source.resolve(strict=True)
    source_fd = os.open(
        source,
        os.O_RDONLY
        | os.O_DIRECTORY
        | getattr(os, "O_CLOEXEC", 0)
        | getattr(os, "O_NOFOLLOW", 0),
    )
    destination_fd = -1
    if destination is not None:
        destination.mkdir(mode=0o700)
        destination_fd = os.open(
            destination,
            os.O_RDONLY
            | os.O_DIRECTORY
            | getattr(os, "O_CLOEXEC", 0)
            | getattr(os, "O_NOFOLLOW", 0),
        )
    digest = hashlib.sha256()
    counters = {"files": 0, "bytes": 0}

    def record(kind: bytes, parts: tuple[str, ...], detail: bytes) -> None:
        path = "/".join(parts).encode("utf-8", errors="strict")
        digest.update(kind + b"\0" + path + b"\0" + detail + b"\n")

    def walk(
        source_directory_fd: int, target_directory_fd: int, prefix: tuple[str, ...]
    ) -> None:
        before = os.fstat(source_directory_fd)
        if (
            not stat.S_ISDIR(before.st_mode)
            or before.st_uid not in {0, os.geteuid()}
            or (stat.S_IMODE(before.st_mode) & 0o022 and not allow_writable_source)
        ):
            raise AuthorityError("runtime tree directory is writable or unowned")
        names = sorted(entry.name for entry in os.scandir(source_directory_fd))
        if any(
            not name or name in {".", ".."} or "/" in name or "\x00" in name
            for name in names
        ):
            raise AuthorityError("runtime tree entry name is unsafe")
        for name in names:
            if omit_python_bytecode and (
                name == "__pycache__" or name.endswith((".pyc", ".pyo"))
            ):
                # This projection is security relevant: omitted bytecode is
                # never copied into the private runtime and the interpreter is
                # invoked with -B, so only the reviewed source can execute.
                continue
            parts = (*prefix, name)
            if len(parts) > 64 or len("/".join(parts).encode()) > 4096:
                raise AuthorityError("runtime tree path exceeds its bound")
            info = os.stat(name, dir_fd=source_directory_fd, follow_symlinks=False)
            if info.st_uid not in {0, os.geteuid()} or (
                stat.S_IMODE(info.st_mode) & 0o022 and not allow_writable_source
            ):
                raise AuthorityError("runtime tree member is writable or unowned")
            if stat.S_ISDIR(info.st_mode):
                record(b"D", parts, b"0500")
                child_source_fd = os.open(
                    name,
                    os.O_RDONLY
                    | os.O_DIRECTORY
                    | getattr(os, "O_CLOEXEC", 0)
                    | getattr(os, "O_NOFOLLOW", 0),
                    dir_fd=source_directory_fd,
                )
                child_target_fd = -1
                try:
                    if target_directory_fd >= 0:
                        os.mkdir(name, 0o700, dir_fd=target_directory_fd)
                        child_target_fd = os.open(
                            name,
                            os.O_RDONLY
                            | os.O_DIRECTORY
                            | getattr(os, "O_CLOEXEC", 0)
                            | getattr(os, "O_NOFOLLOW", 0),
                            dir_fd=target_directory_fd,
                        )
                    walk(child_source_fd, child_target_fd, parts)
                    if child_target_fd >= 0:
                        os.fchmod(child_target_fd, 0o500)
                finally:
                    if child_target_fd >= 0:
                        os.close(child_target_fd)
                    os.close(child_source_fd)
                continue
            if stat.S_ISLNK(info.st_mode):
                target = os.readlink(name, dir_fd=source_directory_fd)
                normalized_target = _normalized_link(prefix, target)
                if normalized_target is None:
                    # Known external development-only links are not part of an
                    # executable -I -S runtime and are omitted from the closed
                    # copy.  Every other escaping link fails closed.
                    if parts[-1] not in {"site-packages", "Headers"}:
                        raise AuthorityError("runtime tree symlink escapes its root")
                    record(b"X", parts, target.encode("utf-8", errors="strict"))
                    continue
                target_raw = target.encode("utf-8", errors="strict")
                if len(target_raw) > 4096:
                    raise AuthorityError("runtime tree symlink target is too long")
                record(b"L", parts, target_raw)
                counters["files"] += 1
                if target_directory_fd >= 0:
                    os.symlink(target, name, dir_fd=target_directory_fd)
                continue
            if (
                not stat.S_ISREG(info.st_mode)
                or not 0 <= info.st_size <= MAX_RUNTIME_FILE_BYTES
            ):
                raise AuthorityError("runtime tree member type/size is forbidden")
            source_member_fd = os.open(
                name,
                os.O_RDONLY
                | getattr(os, "O_CLOEXEC", 0)
                | getattr(os, "O_NOFOLLOW", 0),
                dir_fd=source_directory_fd,
            )
            target_member_fd = -1
            member_digest = hashlib.sha256()
            copied = 0
            executable = bool(stat.S_IMODE(info.st_mode) & 0o111)
            target_mode = 0o500 if executable else 0o400
            try:
                opened = os.fstat(source_member_fd)
                if _file_identity(opened) != _file_identity(info):
                    raise AuthorityError("runtime tree member pathname was substituted")
                if target_directory_fd >= 0:
                    target_member_fd = os.open(
                        name,
                        os.O_WRONLY
                        | os.O_CREAT
                        | os.O_EXCL
                        | getattr(os, "O_CLOEXEC", 0)
                        | getattr(os, "O_NOFOLLOW", 0),
                        0o600,
                        dir_fd=target_directory_fd,
                    )
                while copied < opened.st_size:
                    chunk = os.read(
                        source_member_fd,
                        min(1024 * 1024, opened.st_size - copied),
                    )
                    if not chunk:
                        raise AuthorityError("runtime tree member was truncated")
                    member_digest.update(chunk)
                    copied += len(chunk)
                    if target_member_fd >= 0:
                        view = memoryview(chunk)
                        while view:
                            written = os.write(target_member_fd, view)
                            if written <= 0:
                                raise AuthorityError(
                                    "runtime tree copy made no progress"
                                )
                            view = view[written:]
                if os.read(source_member_fd, 1):
                    raise AuthorityError("runtime tree member grew during copy")
                if _file_identity(os.fstat(source_member_fd)) != _file_identity(opened):
                    raise AuthorityError("runtime tree member changed during copy")
                if target_member_fd >= 0:
                    os.fchmod(target_member_fd, target_mode)
                    os.fsync(target_member_fd)
            finally:
                if target_member_fd >= 0:
                    os.close(target_member_fd)
                os.close(source_member_fd)
            counters["files"] += 1
            counters["bytes"] += copied
            if (
                counters["files"] > MAX_RUNTIME_TREE_FILES
                or counters["bytes"] > MAX_RUNTIME_TREE_BYTES
            ):
                raise AuthorityError("runtime tree exceeds its aggregate bound")
            record(
                b"F",
                parts,
                (b"x" if executable else b"-")
                + b"\0"
                + str(copied).encode()
                + b"\0"
                + member_digest.hexdigest().encode(),
            )
        after_names = sorted(entry.name for entry in os.scandir(source_directory_fd))
        after = os.fstat(source_directory_fd)
        if names != after_names or _file_identity(before) != _file_identity(after):
            raise AuthorityError("runtime tree directory changed during snapshot")

    try:
        record(b"D", (), b"0500")
        walk(source_fd, destination_fd, ())
        if destination_fd >= 0:
            os.fchmod(destination_fd, 0o500)
            os.fsync(destination_fd)
        value: dict[str, int | str] = {
            "sha256": digest.hexdigest(),
            "files": counters["files"],
            "size": counters["bytes"],
        }
        if expected_sha256 is not None and value["sha256"] != expected_sha256:
            raise AuthorityError("runtime tree differs from the reviewed digest")
        return value
    finally:
        if destination_fd >= 0:
            os.close(destination_fd)
        os.close(source_fd)


def _sha(raw: bytes) -> str:
    return hashlib.sha256(raw).hexdigest()


def _pairs(pairs: list[tuple[str, Any]]) -> dict[str, Any]:
    value: dict[str, Any] = {}
    for key, item in pairs:
        if key in value:
            raise AuthorityError("duplicate JSON key")
        value[key] = item
    return value


def _json(raw: bytes, label: str, maximum: int = MAX_COMMAND) -> Any:
    if not 1 <= len(raw) <= maximum:
        raise AuthorityError(f"{label} size is invalid")
    try:
        return json.loads(raw, object_pairs_hook=_pairs)
    except (UnicodeDecodeError, json.JSONDecodeError) as error:
        raise AuthorityError(f"{label} is not strict JSON") from error


def _canonical(value: Any) -> bytes:
    return (
        json.dumps(value, ensure_ascii=True, sort_keys=True, separators=(",", ":"))
        + "\n"
    ).encode()


def _base64_hash(value: Any, length: int, label: str) -> str:
    if not isinstance(value, str) or len(value) > 128:
        raise AuthorityError(f"{label} is invalid")
    try:
        decoded = base64.b64decode(value, validate=True)
    except (ValueError, binascii.Error) as error:
        raise AuthorityError(f"{label} is invalid") from error
    if len(decoded) != length:
        raise AuthorityError(f"{label} is invalid")
    return value


def _exact(value: Any, keys: set[str], label: str) -> dict[str, Any]:
    if not isinstance(value, dict) or set(value) != keys:
        raise AuthorityError(f"{label} schema differs")
    return value


def _run(
    command: list[str],
    *,
    cwd: Path = ROOT,
    env: dict[str, str],
    timeout: int = 60,
    maximum: int = MAX_COMMAND,
) -> bytes:
    command_path = Path(command[0])
    for expected_path, label in ((GH, "GitHub CLI"), (GCLOUD, "gcloud CLI")):
        if command_path == expected_path.resolve(strict=True):
            # macOS cannot portably execute these binaries through /dev/fd.
            # Re-hash the exact resolved pathname immediately before exec.
            _tool(expected_path, label)
            break
    try:
        result = subprocess.run(
            command,
            cwd=cwd,
            env=env,
            stdin=subprocess.DEVNULL,
            capture_output=True,
            check=False,
            timeout=timeout,
        )
    except subprocess.TimeoutExpired as error:
        raise AuthorityError("bounded evidence command timed out") from error
    if len(result.stdout) > maximum or len(result.stderr) > MAX_COMMAND:
        raise AuthorityError("bounded evidence command output exceeded its limit")
    if result.returncode != 0:
        raise AuthorityError(f"evidence command failed with status {result.returncode}")
    return result.stdout


